NOTE = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
NAMES = ["C", "C#", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B"]


def _midi(name):
    pc = NOTE[name[0]] + (1 if name[1] == "#" else -1 if name[1] == "b" else 0)
    return 12 * (int(name[-1]) + 1) + pc


def _up(melody, semis, flats=True):
    out = []
    for p, b in melody:
        if p is None:
            out.append((None, b))
            continue
        m = _midi(p) + semis
        nm = NAMES[m % 12]
        if not flats:
            nm = {"Eb": "D#", "Ab": "G#", "Bb": "A#"}.get(nm, nm)
        out.append((f"{nm}{m // 12 - 1}", b))
    return out


def bars(bpb, *rows):
    out = []
    for i, row in enumerate(rows):
        assert abs(sum(b for _, b in row) - bpb) < 1e-9, (i, row)
        out += row
    return out


def _pd(what):
    return dict(composition=f"public domain ({what}); check before publishing: the melody is typed from memory "
                            "(our own arrangement)", arrangement_license="TBD")


