# M2 part 4 (E): three more songs. Melodies typed bar by bar (bars() checks each bar's length).
def bars(bpb, *rows):
    out = []
    for i, row in enumerate(rows):
        assert abs(sum(b for _, b in row) - bpb) < 1e-9, (i, row)
        out += row
    return out


