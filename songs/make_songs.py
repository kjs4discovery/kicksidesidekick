# ------------------------------------------------------------------ arranging

def swing_tick(t, bar_ticks):
    """straight eighths -> shuffle eighths: the off-beat moves from 1/2 to 2/3 of the beat"""
    beat, frac = divmod(t, PPQ)
    if frac <= PPQ // 2:
        frac = frac * (2 * PPQ // 3) // (PPQ // 2)
    else:
        frac = 2 * PPQ // 3 + (frac - PPQ // 2) * (PPQ // 3) // (PPQ // 2)
    return beat * PPQ + frac


def timeline(s):
    """per bar index: [(start_beat, length_beats, Chord or None)], and the bar count"""
    diag = Diagnostics()
    bars = []
    if s["pickup"]:
        bars.append(parse_chart_text(s["chart"]["pickup"], s["bpb"], "pickup", diag)[0])
    for _, count, part in s["form"]:
        cells = parse_chart_text(s["chart"][part], s["bpb"], part, diag)
        assert len(cells) == count, (s["title"], part)
        bars += cells
    if s["ending"]:
        bars[-1] = parse_chart_text(s["ending"], s["bpb"], "ending", diag)[0]
    assert not diag.errors, [str(d) for d in diag.errors]
    out, last = [], None
    for cells in bars:
        row = []
        for k, (beat, sym) in enumerate(cells):
            end = cells[k + 1][0] if k + 1 < len(cells) else s["bpb"]
            row.append((beat, end - beat, ch.parse_chord(sym)))
        if not row or row[0][0] != 0:            # a bar starting with '.': the chord before goes on
            row.insert(0, (0, row[0][0] if row else s["bpb"], last))
        last = row[-1][2]
        out.append(row)
    return out


def arrange(s):
    bpb = s["bpb"]
    bar_ticks = bpb * PPQ
    bars = timeline(s)
    nbars = len(bars)
    swing = s["feel"] == "swing"
    sw = (lambda t: swing_tick(t, bar_ticks)) if swing else (lambda t: t)
    first_section_bars = {0 if not s["pickup"] else 1}
    acc = 1 if s["pickup"] else 0
    for _, count, _ in s["form"]:
        first_section_bars.add(acc)
        acc += count
    last = nbars - 1
    tracks = {}

    def note(lst, start, dur, pitch, vel):
        a, b = sw(start), sw(start + dur)
        lst.append((a, max(a + 10, b - 15), pitch, vel))

    # ---- melody
    mel, t = [], (bpb - s["pickup"]) * PPQ if s["pickup"] else 0
    for pitch, beats in s["melody"]:
        d = int(round(beats * PPQ))
        if pitch is not None:
            note(mel, t, d, n(pitch), 90)
        t += d
    assert t == nbars * bar_ticks, (s["title"], t / PPQ, nbars * bpb)
    tracks["melody:1"] = mel

    v2_prev = None
    for level in (1, 2):
        harm, bass, drums = [], [], []
        v2_prev = None
        for b, row in enumerate(bars):
            t0 = b * bar_ticks
            final = b == last
            for beat, length, c in row:
                if c is None:
                    continue
                start, dur = t0 + beat * PPQ, length * PPQ
                v1 = ch.voicing_level1(c)
                v2 = ch.voicing_level2(c, v2_prev)
                v2_prev = v2
                root = 36 + c.root if c.root >= 4 else 48 + c.root          # E2..D#3
                if c.bass is not None:
                    root = 36 + c.bass if c.bass >= 4 else 48 + c.bass
                fifth = root + 7 if root + 7 <= 52 else root - 5
                # harmony
                style = s["style"]["harmony"]
                if level == 1 or final:
                    for p in (v1 if level == 1 else v2):
                        note(harm, start, dur, p, 64)
                elif style == "waltz":
                    for k in range(length):
                        for p in v2:
                            note(harm, start + k * PPQ, PPQ - 40 if k % 3 == 0 else PPQ // 2, p, 64 if k % 3 == 0 else 50)
                elif style == "shuffle":
                    for k in range(length):
                        for p in v2:
                            note(harm, start + k * PPQ, PPQ // 3, p, 58 if k % 2 else 50)
                elif style == "stride":
                    for k in range(length):
                        beat_in_bar = beat + k
                        for p in (v2 if beat_in_bar % 2 else [root + 12]):
                            note(harm, start + k * PPQ, PPQ // 2, p, 60 if beat_in_bar % 2 else 54)
                elif style == "arpeggio":                                     # the voicing broken into eighths
                    for k in range(length * 2):
                        p = v2[k % len(v2)] if (k // len(v2)) % 2 == 0 else v2[-1 - k % len(v2)]
                        note(harm, start + k * PPQ // 2, PPQ // 2 + 60, p, 58 if k % 2 == 0 else 48)
                else:                                                         # straight eighths
                    for k in range(length * 2):
                        for p in v2:
                            note(harm, start + k * PPQ // 2, PPQ // 3, p, 56 if k % 2 == 0 else 44)
                # bass
                style = s["style"]["bass"]
                if level == 1 or final:
                    note(bass, start, dur, root, 84)
                elif style == "root-fifth" or style == "two-beat":
                    half = 2 if bpb % 2 == 0 else 2
                    for k in range(0, length, half):
                        p = root if (beat + k) % bpb == 0 or k == 0 else fifth
                        note(bass, start + k * PPQ, min(half, length - k) * PPQ, p, 88 if p == root else 76)
                elif style == "boogie":
                    line = [0, 4, 7, 9, 10, 9, 7, 4]
                    for k in range(length * 2):
                        note(bass, start + k * PPQ // 2, PPQ // 2, root + line[(beat * 2 + k) % 8], 84 if k % 2 == 0 else 70)
                else:                                                         # eighths
                    for k in range(length * 2):
                        note(bass, start + k * PPQ // 2, PPQ // 2, root, 86 if k % 2 == 0 else 72)
            # drums, per bar
            style = s["style"]["drums"]
            if b == 0 and s["pickup"]:
                continue
            if final:
                drums += [(t0, 60, KICK, 96), (t0, 60, CRASH, 90)]
                continue
            if s.get("contrast"):        # M2: level 1 just the beat, level 2 clearly busier (user feedback)
                drums += contrast_drums(s, style, level, b, t0, b in first_section_bars and b > (1 if s["pickup"] else 0))
                continue
            if b in first_section_bars and b > (1 if s["pickup"] else 0):
                drums.append((t0, 60, CRASH, 76))
            fill = level == 2 and (b + 1 - (1 if s["pickup"] else 0)) % (4 if style == "shuffle" else 8) == 0
            if style == "waltz":
                drums.append((t0, 60, KICK, 72))
                for k in range(bpb):
                    drums.append((t0 + k * PPQ, 60, HAT, 50 if k else 60))
                if level == 2:
                    drums += [(t0 + PPQ, 60, STICK, 44), (t0 + 2 * PPQ, 60, STICK, 44)]
                    if fill:
                        drums += [(t0 + 2 * PPQ, 60, SNARE, 60), (t0 + 2 * PPQ + PPQ // 2, 60, SNARE, 70)]
            else:
                for k in range(bpb):
                    tk = t0 + k * PPQ
                    if k % 2 == 0:
                        drums.append((tk, 60, KICK, 80 if k == 0 else 70))
                    else:
                        drums.append((tk, 60, SNARE, 74))
                    cym = RIDE if style == "shuffle" else HAT
                    drums.append((tk, 60, cym, 56 if k % 2 else 64))
                    if level == 2:
                        if style in ("shuffle", "march", "pop"):
                            drums.append((sw(tk + PPQ // 2), 40, cym, 42))
                        if style == "pop" and k == 2:
                            drums.append((tk + PPQ // 2, 60, KICK, 62))
                        if style == "shuffle" and k % 2 == 0:
                            drums.append((sw(tk + PPQ // 2), 40, SNARE, 26))
                if fill:
                    base = t0 + (bpb - 1) * PPQ
                    for k, p in enumerate((SNARE, SNARE, TOM_HI, TOM_LO)):
                        drums.append((sw(base + k * PPQ // 4) if not swing else base + k * PPQ // 4, 50, p, 64 + 4 * k))
                if level == 2 and style == "march" and b % 2 == 1:
                    drums.append((sw(t0 + 3 * PPQ + PPQ // 2), 40, SNARE, 50))
        tracks[f"harmony:{level}"] = harm
        tracks[f"bass:{level}"] = bass
        tracks[f"drums:{level}"] = [(a, a + d, p, v) for a, d, p, v in drums]
    return tracks, nbars


def contrast_drums(s, style, level, b, t0, section_start):
    """the new songs' drums (M2): level 1 the plain pulse, level 2 a full groove with fills; (tick, len, drum, vel)"""
    bpb, out = s["bpb"], []
    if level == 1:
        out.append((t0, 60, KICK, 70))
        if bpb == 4:
            out.append((t0 + 2 * PPQ, 60, KICK, 60))
        for k in range(bpb):
            out.append((t0 + k * PPQ, 60, PEDAL_HAT if style == "waltz" else HAT, 46 if k else 56))
        return out
    bar_no = b + 1 - (1 if s["pickup"] else 0)
    fill = bar_no % 4 == 0
    if section_start:
        out.append((t0, 80, CRASH, 84))
    if style == "waltz":
        out.append((t0, 60, KICK, 84))
        for k in range(bpb):
            for h in range(2):
                out.append((t0 + k * PPQ + h * PPQ // 2, 40, HAT, (62 if k == 0 else 50) if h == 0 else 36))
            if k:
                out.append((t0 + k * PPQ, 60, STICK, 58))
        if fill:
            out += [(t0 + 2 * PPQ + i * PPQ // 4, 50, p, 62 + 6 * i) for i, p in enumerate((SNARE, SNARE, TOM_HI, TOM_LO))]
        return out
    for k in range(bpb):
        tk = t0 + k * PPQ
        if k in (0, 2):
            out.append((tk, 60, KICK, 92 if k == 0 else 80))
        else:
            out.append((tk, 60, STICK if style == "ballad" else SNARE, 70 if style == "ballad" else 88))
        for h in range(2):
            out.append((tk + h * PPQ // 2, 40, HAT, (66 if k % 2 == 0 else 58) if h == 0 else 40))
        if style == "train":
            out += [(tk + PPQ // 4, 30, SNARE, 24), (tk + 3 * PPQ // 4, 30, SNARE, 30)]
            if k == 1:
                out.append((tk + PPQ // 2, 60, KICK, 64))
    if style == "train" and bar_no % 2 == 0:
        out.append((t0 + (bpb - 1) * PPQ + PPQ // 2, 60, OPEN_HAT, 52))
    if fill:
        base = t0 + (bpb - 1) * PPQ
        out += [(base + i * PPQ // 4, 50, p, 64 + 6 * i) for i, p in enumerate((SNARE, SNARE, TOM_HI, TOM_LO))]
    return out


def build_midi(s, tracks):
    sharps = {"C": 0, "G": 1, "D": 2, "A": 3, "E": 4, "F": -1, "Bb": -2, "Eb": -3, "Am": 0}
    key = s["key"] if not s["mode"] else {"dorian": "C"}.get(s["mode"], s["key"])   # D dorian: no sharps/flats
    conductor = [(0, meta_tempo(round(60_000_000 / s["tempo"]))), (0, meta_timesig(s["bpb"], 4)),
                 (0, meta_key(sharps.get(key, 0), 0))]
    out = [("conductor", conductor)]
    programs = dict(s["layers"])
    order = ["melody:1", "harmony:1", "harmony:2", "bass:1", "bass:2", "drums:1", "drums:2"]
    for name in order:
        layer = name.split(":")[0]
        chan = CHANNELS[layer] - 1
        evs = []
        if layer in programs:
            evs.append((0, bytes([0xC0 | chan, programs[layer] - 1])))
        # note-offs first at a tick: sort by (tick, on?) through the writer's stable sort
        raw = []
        for start, end, pitch, vel in ((a, b, p, v) for a, b, p, v in _ends(tracks[name])):
            raw.append((start, 1, bytes([0x90 | chan, pitch, vel])))
            raw.append((end, 0, bytes([0x80 | chan, pitch, 0])))
        raw.sort(key=lambda e: (e[0], e[1], e[2]))
        evs += [(t, b) for t, _, b in raw]
        out.append((name if layer != "melody" else "melody", evs))
    return write_midi(PPQ, out)


def _ends(notes):
    """(start, end, pitch, vel) sorted; a note that would overlap the next one of the same pitch ends there"""
    seen, out = set(), []
    for a, e, p, v in sorted(notes, key=lambda x: (x[0], x[2], -x[3])):
        if (a, p) not in seen:                      # two hits of one drum at one tick: keep the louder
            seen.add((a, p))
            out.append((a, e, p, v))
    last = {}
    for i, (a, e, p, v) in enumerate(out):
        if p in last and out[last[p]][1] > a:
            j = last[p]
            out[j] = (out[j][0], a, p, out[j][3])
        last[p] = i
    return out


def yaml_text(slug, s):
    first = 1
    form = []
    for name, count, part in s["form"]:
        form.append(f"  - {{ section: {name}, bars: {first}-{first + count - 1}, chart: {part} }}")
        first += count
    key_lines = f"  key: {s['key']}\n" + (f"  mode: {s['mode']}\n" if s["mode"] else "")
    lay = []
    for layer in ("drums", "bass", "harmony", "melody"):
        lay.append(f"  {layer}:\n    channel: {CHANNELS[layer]}")
        if layer in s["layers"]:
            lay.append(f"    program: {s['layers'][layer]}")
        lay.append("    variants:")
        for k, d in s["variants"][layer].items():
            lay.append(f"      {k}: {d}")
    chart = []
    for part, text in s["chart"].items():
        if "\n" in text:
            chart.append(f"  {part}: |\n" + "\n".join("    " + line for line in text.splitlines()))
        else:
            chart.append(f'  {part}: "{text}"')
    if s["ending"]:
        chart.append(f'  ending: "{s["ending"]}"                   # replaces the last bar of the song')
    q = lambda x: "'" + x.replace("'", "''") + "'"
    return f"""# Song source file, format fm1-song/1 (docs/song-format.md).
# GENERATED by songs/make_songs.py: edit that script, not this file (D004).
format: fm1-song/1
slug: {slug}
title: {s['title']}

credits:
  music: {q(s['credits']['music'])}
  arrangement: {q(s['credits']['arrangement'])}

rights:
  composition: {q(s['rights']['composition'])}
  arrangement_license: {s['rights']['arrangement_license']}
  generated: make_songs.py

music:
{key_lines}  time_signature: {s['bpb']}/4
  tempo_bpm: {s['tempo']}
  pickup_beats: {s['pickup']}
  feel: {s['feel']}

form:
{chr(10).join(form)}

layers:
{chr(10).join(lay)}

chart:
{chr(10).join(chart)}
"""


def main(argv):
    preview = "--preview" in argv
    wanted = [a for a in argv if not a.startswith("--")] or list(SONGS)
    for slug in wanted:
        s = SONGS[slug]
        folder = HERE / slug
        folder.mkdir(exist_ok=True)
        tracks, _ = arrange(s)
        (folder / "song.mid").write_bytes(build_midi(s, tracks))
        (folder / "song.yaml").write_text(yaml_text(slug, s))
        print(f"wrote {slug}/song.mid, song.yaml")
        if preview:
            from fm1song import compile_folder, read_compiled
            from fm1song.preview import render, write_audio
            compiled = read_compiled(compile_folder(folder)[0])
            (folder / "previews").mkdir(exist_ok=True)
            write_audio(render(compiled, {k: 1 for k in compiled["layers"]}),
                        folder / "previews" / "preview-full-band-level1.mp3")
            write_audio(render(compiled, {"melody": 1, "bass": 2, "drums": 2}),
                        folder / "previews" / "preview-harmony-muted-level2.mp3")
            print(f"wrote {slug}/previews")


if __name__ == "__main__":
    main(sys.argv[1:])
