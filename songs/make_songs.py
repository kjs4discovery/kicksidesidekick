def arrange(s):
    """the melody (typed in) and every generated level: harmony 1-5, bass 1-4, drums 1-3 (D026)"""
    bpb = s["bpb"]
    bar_ticks = bpb * PPQ
    bars = arr.timeline(s["chart"], s["form"], s["pickup"], bpb, s["ending"])
    nbars = len(bars)
    section_starts, acc = set(), 1 if s["pickup"] else 0
    for _, count, _ in s["form"]:
        section_starts.add(acc)
        acc += count
    section_starts.discard(1 if s["pickup"] else 0)        # (no crash on the very first bar)
    swing = s["feel"] == "swing"
    sw = arr.swing_tick if swing else (lambda t: t)
    mel, t = [], (bpb - s["pickup"]) * PPQ if s["pickup"] else 0
    for pitch, beats in s["melody"]:
        d = int(round(beats * PPQ))
        if pitch is not None:
            a, e = sw(t), sw(t + d)
            mel.append((a, max(a + 10, e - 15), n(pitch), 90))
        t += d
    assert t <= nbars * bar_ticks, (s["title"], t / PPQ, nbars * bpb)   # (a melody may end before the last bar ends)
    tracks = {"melody:1": mel}           # (M5, format 2.0: the FM-1 generates the rest from the chart and the style)
    return tracks, nbars


def melody_from_midi(path, pickup_beats, bpb):
    """a song.mid's melody track as [(pitch name or None, beats)] from the first bar line on (Amazing Grace: the
    planning chat's sample melody, kept as it is)"""
    m = read_midi(Path(path).read_bytes())
    tr = next(t for t in m.tracks if t.name == "melody")
    on = sorted((e.tick, e.a) for e in tr.events if e.kind == "on" and e.b > 0)
    off = {}
    for e in tr.events:
        if e.kind == "off" or (e.kind == "on" and e.b == 0):
            off.setdefault(e.a, []).append(e.tick)
    g = m.ppq // 4                                       # starts and ends on a sixteenth grid
    snap = lambda x: (x + g // 2) // g * g
    out, t = [], (bpb - pickup_beats) * m.ppq if pickup_beats else 0
    for k, (tick, pitch) in enumerate(on):
        tick = snap(tick)
        end = snap(min(x for x in off[pitch] if x > tick - g))
        nxt = snap(on[k + 1][0]) if k + 1 < len(on) else None
        if nxt is not None and (end > nxt or nxt - end < g * 2):
            end = nxt                                    # (shortened notes: legato up to the next one)
        if tick > t:
            out.append((None, (tick - t) / m.ppq))
        out.append((ch.note_name(pitch), max(end - tick, g) / m.ppq))
        t = tick + max(end - tick, g)
    return out


def build_midi(s, tracks):
    sharps = {"C": 0, "G": 1, "D": 2, "A": 3, "E": 4, "F": -1, "Bb": -2, "Eb": -3, "Am": 0}
    key = s["key"] if not s["mode"] else {"dorian": "C"}.get(s["mode"], s["key"])   # D dorian: no sharps/flats
    conductor = [(0, meta_tempo(round(60_000_000 / s["tempo"]))), (0, meta_timesig(s["bpb"], 4)),
                 (0, meta_key(sharps.get(key, 0), 0))]
    out = [("conductor", conductor)]
    programs = dict(s["layers"])
    order = [n for n in ["melody:1"] + [f"harmony:{k}" for k in range(1, 6)] + [f"bass:{k}" for k in range(1, 5)]
             + [f"drums:{k}" for k in range(1, 4)] if n in tracks]
    for name in order:
        layer = name.split(":")[0]
        chan = CHANNELS[layer] - 1
        evs = []
        if layer in programs:
            evs.append((0, bytes([0xC0 | chan, programs[layer] - 1])))
        # note-offs first at a tick: sort by (tick, on?) through the writer's stable sort
        raw = []
        for start, end, pitch, vel in ((a, b, p, v) for a, b, p, v in _ends(tracks[name])):
            raw.append((start, 1, bytes([0x90 | chan, pitch, vel])))
            raw.append((end, 0, bytes([0x80 | chan, pitch, 0])))
        raw.sort(key=lambda e: (e[0], e[1], e[2]))
        evs += [(t, b) for t, _, b in raw]
        out.append((name if layer != "melody" else "melody", evs))
    return write_midi(PPQ, out)


def _ends(notes):
    """(start, end, pitch, vel) sorted; a note that would overlap the next one of the same pitch ends there"""
    seen, out = set(), []
    for a, e, p, v in sorted(notes, key=lambda x: (x[0], x[2], -x[3])):
        if (a, p) not in seen:                      # two hits of one drum at one tick: keep the louder
            seen.add((a, p))
            out.append((a, e, p, v))
    last = {}
    for i, (a, e, p, v) in enumerate(out):
        if p in last and out[last[p]][1] > a:
            j = last[p]
            out[j] = (out[j][0], a, p, out[j][3])
        last[p] = i
    return out


def yaml_text(slug, s):
    first = 1
    form = []
    for name, count, part in s["form"]:
        form.append(f"  - {{ section: {name}, bars: {first}-{first + count - 1}, chart: {part} }}")
        first += count
    key_lines = f"  key: {s['key']}\n" + (f"  mode: {s['mode']}\n" if s["mode"] else "")
    lay = []
    for layer in ("drums", "bass", "harmony", "melody"):
        lay.append(f"  {layer}:\n    channel: {CHANNELS[layer]}")
        if layer in s["layers"]:
            lay.append(f"    program: {s['layers'][layer]}")
        lay.append("    variants:")
        texts = s["variants"]["melody"] if layer == "melody" else arr.LEVEL_TEXT[layer]
        for k, d in texts.items():
            lay.append(f"      {k}: {d}")
    chart = []
    for part, text in s["chart"].items():
        if "\n" in text:
            chart.append(f"  {part}: |\n" + "\n".join("    " + line for line in text.splitlines()))
        else:
            chart.append(f'  {part}: "{text}"')
    if s["ending"]:
        chart.append(f'  ending: "{s["ending"]}"                   # replaces the last bar of the song')
    q = lambda x: "'" + x.replace("'", "''") + "'"
    info_line = f"info: {q(s['info'])}\n" if s.get("info") else ""        # M10 (D062): the song info line (INFO chunk)
    return f"""# Song source file, format fm1-song/1 (docs/song-format.md).
# GENERATED by songs/make_songs.py: edit that script, not this file (D004).
format: fm1-song/1
slug: {slug}
title: {s['title']}
category: {s['category']}
{info_line}
credits:
  music: {q(s['credits']['music'])}
  arrangement: {q(s['credits']['arrangement'])}

rights:
  composition: {q(s['rights']['composition'])}
  arrangement_license: {s['rights']['arrangement_license']}
  generated: make_songs.py

music:
{key_lines}  time_signature: {s['bpb']}/4
  tempo_bpm: {s['tempo']}
  pickup_beats: {s['pickup']}
  feel: {s['feel']}
  style: {s['style']}                  # the FM-1 generates harmony 1-5, bass 1-4, drums 1-3 (D029)

form:
{chr(10).join(form)}

layers:
{chr(10).join(lay)}

chart:
{chr(10).join(chart)}
"""


