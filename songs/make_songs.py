def n(name):
    """'Bb4' -> 70, 'F#3' -> 54"""
    pc = NOTE[name[0]] + (1 if name[1] == "#" else -1 if name[1] == "b" else 0)
    return 12 * (int(name[-1]) + 1) + pc


