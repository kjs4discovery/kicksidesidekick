#!/usr/bin/env python3
"""Generate the Amazing Grace sample song (draft source format v0.1).

Writes, next to this script:
  song.mid            multi-track MIDI in the project's source conventions
and, with --preview (needs numpy; ffmpeg optional for mp3):
  previews/preview-full-band-level1.(mp3|wav)
  previews/preview-harmony-muted-level2.(mp3|wav)

Pure standard library for the MIDI part, so it runs anywhere.
Tune "New Britain" and John Newton's text (1779) are public domain; this
arrangement was generated by the FM-1 Accompaniment project (licence: TBD).
"""
import struct, sys, os, subprocess, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
PPQ = 480
BEATS_PER_BAR = 3
BAR = PPQ * BEATS_PER_BAR
TEMPO_BPM = 84

# ---------------------------------------------------------------- music data
N = {n: i for i, n in enumerate("C C# D D# E F F# G G# A A# B".split())}
def note(name):            # "G4" -> 67, "F#3" -> 54
    pitch, octave = name[:-1], int(name[-1])
    return 12 * (octave + 1) + N[pitch]

# Melody of one verse, bars 1..16, as (note, beats). Bars 7-8 and 15-16 are tied.
VERSE_MELODY = [
    [("G4", 2), ("B4", .5), ("G4", .5)],   # 1  ma-  zing
    [("B4", 2), ("A4", 1)],                # 2  grace how
    [("G4", 2), ("E4", 1)],                # 3  sweet the
    [("D4", 2), ("D4", 1)],                # 4  sound that
    [("G4", 2), ("B4", .5), ("G4", .5)],   # 5  saved a
    [("B4", 2), ("A4", 1)],                # 6  wretch like
    [("D5", 5)],                           # 7-8 me ...
    [("B4", 1)],                           #   (bar 8 beat 3)  I
    [("D5", 2), ("B4", .5), ("G4", .5)],   # 9  once was
    [("B4", 2), ("A4", 1)],                # 10 lost but
    [("G4", 2), ("E4", 1)],                # 11 now am
    [("D4", 2), ("D4", 1)],                # 12 found, was
    [("G4", 2), ("B4", .5), ("G4", .5)],   # 13 blind but
    [("B4", 2), ("A4", 1)],                # 14 now I
    [("G4", 5)],                           # 15-16 see
]
# Notes that start a new syllable (False = melisma continuation), per verse note order
SYLLABLE_START = [True,  # pickup
                  True, True, False, True, True, True, True, True, True,
                  True, True, False, True, True, True, True,
                  True, True, False, True, True, True, True, True, True,
                  True, True, False, True, True, True]
LYRICS = [
    "A ma zing grace how sweet the sound that saved a wretch like me "
    "I once was lost but now am found was blind but now I see".split(),
    "'Twas grace that taught my heart to fear and grace my fears re lieved "
    "how pre cious did that grace ap pear the hour I first be lieved".split(),
]

# Chord chart, one token per beat-group. "." extends the previous chord by a beat.
CHART = {
    0: ["N.C."],
    "verse": ["G", "G7", "C", "G", "G", "Em", "D", "D7",
              "G", "G7", "C", "G", "Em", "D", "G", "G . D7"],
}

# Voicings per difficulty: level 1 = root position, level 2 = voice-led inversions
VOICING = {
    1: {"G": "G3 B3 D4", "G7": "G3 B3 D4 F4", "C": "C4 E4 G4",
        "Em": "E3 G3 B3", "D": "D3 F#3 A3", "D7": "D3 F#3 A3 C4"},
    2: {"G": "G3 B3 D4", "G7": "F3 G3 B3 D4", "C": "G3 C4 E4",
        "Em": "G3 B3 E4", "D": "F#3 A3 D4", "D7": "F#3 A3 C4 D4"},
}
BASS_ROOT = {"G": "G2", "G7": "G2", "C": "C3", "Em": "E2", "D": "D2", "D7": "D2"}
BASS_FIFTH = {"G": "D3", "G7": "D3", "C": "G2", "Em": "B2", "D": "A2", "D7": "A2"}

VERSES = 2
TOTAL_BARS = 1 + 16 * VERSES          # bar 0 = pickup bar

# ---------------------------------------------------------------- build events
def chord_spans():
    """[(start_tick, length_ticks, symbol)] for the whole song."""
    spans = []
    def add_bar(bar, text):
        toks = text.split()
        each = BAR // len(toks) if "." not in toks else PPQ
        t = bar * BAR
        for tok in toks:
            if tok == "." and spans:
                s, l, sym = spans[-1]
                spans[-1] = (s, l + PPQ, sym)
            else:
                length = PPQ if "." in toks else each
                spans.append((t, length, tok))
            t += PPQ if "." in toks else each
    add_bar(0, CHART[0][0])
    for v in range(VERSES):
        for i, text in enumerate(CHART["verse"]):
            bar = 1 + 16 * v + i
            if v == VERSES - 1 and i == 15:
                text = "G"               # final bar: no turnaround
            add_bar(bar, text)
    # merge bar-length duplicates? No: one span per chart token keeps it simple.
    return spans

def melody_notes():
    """[(start, dur, pitch, lyric_or_None)]"""
    out = []
    pickup_tick = 2 * PPQ                      # bar 0 beat 3
    for v in range(VERSES):
        lyr = iter(LYRICS[v])
        flags = iter(SYLLABLE_START)
        start = pickup_tick if v == 0 else (16 * v) * BAR + 2 * PPQ
        out.append((start, PPQ, note("D4"), next(lyr) if next(flags) else None))
        t = (1 + 16 * v) * BAR
        for group in VERSE_MELODY:
            for name, beats in group:
                dur = int(beats * PPQ)
                if v == VERSES - 1 and name == "G4" and beats == 5:
                    dur = 6 * PPQ              # last note held to the end
                out.append((t, dur, note(name), next(lyr) if next(flags) else None))
                t += dur if not (v == VERSES - 1 and beats == 5) else 5 * PPQ
    return out

def harmony_notes(level):
    out = []
    for start, length, sym in chord_spans():
        if sym == "N.C.":
            continue
        pitches = [note(n) for n in VOICING[level][sym].split()]
        if level == 1 or length < BAR:          # block chord held
            out += [(start, length - 20, p, 62) for p in pitches]
        else:                                    # waltz: beat 1 long-ish, 2 & 3 short
            out += [(start, PPQ - 40, p, 64) for p in pitches]
            out += [(start + PPQ, PPQ // 2, p, 50) for p in pitches]
            out += [(start + 2 * PPQ, PPQ // 2, p, 50) for p in pitches]
    return out

def bass_notes(level):
    out, spans = [], chord_spans()
    for i, (start, length, sym) in enumerate(spans):
        if sym == "N.C.":
            continue
        root = note(BASS_ROOT[sym])
        if level == 1 or length < BAR:
            out.append((start, length - 20, root, 84))
        else:
            out.append((start, 2 * PPQ - 20, root, 88))
            out.append((start + 2 * PPQ, PPQ - 20, note(BASS_FIFTH[sym]), 76))
    return out

KICK, STICK, SNARE, HAT, RIDE, CRASH = 36, 37, 38, 42, 51, 49
def drum_notes(level):
    out = []
    last = TOTAL_BARS - 1
    for bar in range(1, TOTAL_BARS):
        t = bar * BAR
        if bar == last:
            out += [(t, 60, KICK, 90), (t, 60, CRASH, 80)]
            continue
        out.append((t, 60, KICK, 72))
        for b in range(3):
            out.append((t + b * PPQ, 60, RIDE, 52 if b else 62))
        if level == 2:
            out += [(t + PPQ, 60, STICK, 44), (t + 2 * PPQ, 60, STICK, 44)]
            if bar % 8 == 0:                       # small fill into the next phrase
                out += [(t + 2 * PPQ, 60, SNARE, 60), (t + 2 * PPQ + PPQ // 2, 60, SNARE, 70)]
            out.append((t + 2 * PPQ + PPQ // 2, 40, HAT, 36))
    return out

# ---------------------------------------------------------------- SMF writer
def vlq(n):
    b = [n & 0x7F]
    n >>= 7
    while n:
        b.insert(0, (n & 0x7F) | 0x80)
        n >>= 7
    return bytes(b)

def meta(kind, data):
    return bytes([0xFF, kind]) + vlq(len(data)) + data

def track(name, events):
    """events: [(tick, priority, bytes)]; lower priority first at same tick."""
    evs = [(0, -1, meta(0x03, name.encode()))] + events
    evs.sort(key=lambda e: (e[0], e[1]))
    out, last = b"", 0
    for tick, _, data in evs:
        out += vlq(tick - last) + data
        last = tick
    out += vlq(0) + meta(0x2F, b"")
    return b"MTrk" + struct.pack(">I", len(out)) + out

def note_events(notes, ch, program=None, lyrics=False):
    evs = []
    if program is not None:
        evs.append((0, 0, bytes([0xC0 | ch, program])))
    for n in notes:
        start, dur, pitch = n[0], n[1], n[2]
        vel = n[3] if not lyrics and len(n) > 3 else 92
        if lyrics and n[3]:
            evs.append((start, 1, meta(0x05, n[3].encode())))
        evs.append((start, 2, bytes([0x90 | ch, pitch, vel])))
        evs.append((start + dur, 0, bytes([0x80 | ch, pitch, 0])))
    return evs

def build_midi():
    tempo = 60_000_000 // TEMPO_BPM
    conductor = [
        (0, 0, meta(0x51, tempo.to_bytes(3, "big"))),
        (0, 0, meta(0x58, bytes([3, 2, 24, 8]))),        # 3/4
        (0, 0, meta(0x59, bytes([1, 0]))),               # G major
        (0, 1, meta(0x06, b"[Pickup]")),
    ] + [((1 + 16 * v) * BAR, 1, meta(0x06, f"[Verse {v + 1}]".encode())) for v in range(VERSES)]
    chords = [(s, 1, meta(0x01, sym.encode())) for s, _, sym in chord_spans()]
    tracks = [
        track("conductor", conductor),
        track("chords", chords),
        track("melody", note_events(melody_notes(), 0, program=73, lyrics=True)),     # flute
        track("harmony:1", note_events(harmony_notes(1), 1, program=4)),              # e-piano
        track("harmony:2", note_events(harmony_notes(2), 1, program=4)),
        track("bass:1", note_events(bass_notes(1), 2, program=32)),                   # acoustic bass
        track("bass:2", note_events(bass_notes(2), 2, program=32)),
        track("drums:1", note_events(drum_notes(1), 9)),
        track("drums:2", note_events(drum_notes(2), 9)),
    ]
    header = b"MThd" + struct.pack(">IHHH", 6, 1, len(tracks), PPQ)
    return header + b"".join(tracks)

# ---------------------------------------------------------------- preview synth
def render(path, layers, count_in=True, sr=22050):
    import numpy as np
    sec_per_tick = 60.0 / TEMPO_BPM / PPQ
    lead = (BAR + 2 * PPQ) if count_in else 0      # 1 bar + 2 beats of clicks, then the pickup
    total = (TOTAL_BARS * BAR + lead) * sec_per_tick + 2.5
    out = np.zeros(int(total * sr))
    def place(sig, tick):
        i = int((tick + lead) * sec_per_tick * sr)
        j = min(len(out), i + len(sig))
        out[i:j] += sig[: j - i]
    def tone(freq, dur, kind):
        t = np.arange(int((dur + 0.6) * sr)) / sr
        if kind == "flute":
            vib = 1 + 0.004 * np.sin(2 * np.pi * 5 * t)
            s = np.sin(2 * np.pi * freq * vib * t) + 0.25 * np.sin(4 * np.pi * freq * t)
            env = np.minimum(t / 0.06, 1) * np.where(t < dur, 1, np.exp(-(t - dur) / 0.08))
            return 0.28 * s * env
        if kind == "epiano":
            s = sum(a * np.sin(2 * np.pi * freq * k * t) * np.exp(-t * k * 1.2)
                    for k, a in ((1, 1), (2, .4), (3, .15)))
            env = np.minimum(t / 0.005, 1) * np.where(t < dur, 1, np.exp(-(t - dur) / 0.1))
            return 0.16 * s * env
        if kind == "bass":
            s = np.sin(2 * np.pi * freq * t) + 0.5 * np.sin(4 * np.pi * freq * t)
            env = np.minimum(t / 0.01, 1) * np.exp(-t * 1.5) * np.where(t < dur, 1, np.exp(-(t - dur) / 0.06))
            return 0.4 * s * env
    rng = np.random.default_rng(1)
    def drum(n):
        t = np.arange(int(1.3 * sr)) / sr
        noise = rng.standard_normal(len(t))
        if n == KICK:
            f = 50 + 70 * np.exp(-t / 0.04)
            return 0.8 * np.sin(2 * np.pi * np.cumsum(f) / sr) * np.exp(-t / 0.18)
        if n in (RIDE, HAT):
            hp = np.diff(noise, prepend=0)
            return (0.05 if n == RIDE else 0.04) * hp * np.exp(-t / (0.35 if n == RIDE else 0.05))
        if n == STICK:
            return 0.12 * np.diff(noise, prepend=0) * np.exp(-t / 0.015)
        if n == SNARE:
            return (0.12 * noise + 0.2 * np.sin(2 * np.pi * 185 * t)) * np.exp(-t / 0.09)
        if n == CRASH:
            return 0.08 * np.diff(noise, prepend=0) * np.exp(-t / 1.0)
        return 0 * t
    freq = lambda p: 440 * 2 ** ((p - 69) / 12)
    if count_in:
        t = np.arange(int(0.05 * sr)) / sr
        for b in range(BEATS_PER_BAR + 2):
            f = 1500 if b in (0, BEATS_PER_BAR) else 1000
            place(0.3 * np.sin(2 * np.pi * f * t) * np.exp(-t / 0.015), b * PPQ - lead)
    sec = lambda ticks: ticks * sec_per_tick
    if "melody" in layers:
        for s, d, p, _ in melody_notes():
            place(tone(freq(p), sec(d), "flute"), s)
    for name, fn, kind in (("harmony", harmony_notes, "epiano"), ("bass", bass_notes, "bass")):
        if name in layers:
            for s, d, p, v in fn(layers[name]):
                place(tone(freq(p), sec(d), kind) * v / 80, s)
    if "drums" in layers:
        for s, _, p, v in drum_notes(layers["drums"]):
            place(drum(p) * v / 80, s)
    out /= max(1e-9, np.abs(out).max()) / 0.9
    import wave
    wav = path + ".wav"
    with wave.open(wav, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr)
        w.writeframes((out * 32767).astype("<i2").tobytes())
    if shutil.which("ffmpeg"):
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", wav, "-b:a", "96k", path + ".mp3"], check=True)
        os.remove(wav)

if __name__ == "__main__":
    with open(os.path.join(HERE, "song.mid"), "wb") as f:
        f.write(build_midi())
    print("wrote song.mid")
    if "--preview" in sys.argv:
        os.makedirs(os.path.join(HERE, "previews"), exist_ok=True)
        render(os.path.join(HERE, "previews", "preview-full-band-level1"),
               {"melody": 1, "harmony": 1, "bass": 1, "drums": 1})
        render(os.path.join(HERE, "previews", "preview-harmony-muted-level2"),
               {"melody": 1, "bass": 2, "drums": 2})
        print("wrote previews")
