#!/usr/bin/env python3
# jam_songs.py -- M6 part 3: SYNTH mode's drum jam patterns. For each style of the learning engine (arrange.STYLES:
# waltz ballad shuffle march pop train) a tiny format-2.0 song: 8 bars of one chord plus the closing bar, drums
# only (the FM-1 generates its drums L1-3 from the style, as for any song: firmware/app/gen.c). Compiled here by the
# song compiler and written as C arrays into firmware/app/jam_songs.h; the firmware opens them like a stored song
# and loops bars 1-8 of their drums under the synth. Licence: TBD (see D017)
#
#   .venv/bin/python -I tools/jam_songs.py            (writes firmware/app/jam_songs.h, committed; run it again after
#                                                     changing the song format or the styles)
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from fm1song import compile_folder                          # noqa: E402
from fm1song.arrange import STYLE_NAMES                     # noqa: E402
from fm1song.smf import meta_tempo, meta_timesig, write_midi   # noqa: E402

TEMPO = {"waltz": 96, "ballad": 72, "shuffle": 110, "march": 104, "pop": 112, "train": 150}
BARS = 8


def yaml_of(style):
    bpb = 3 if style == "waltz" else 4
    row = " ".join(["| C"] * 4) + " |"
    return f"""format: fm1-song/1
slug: jam-{style}
title: Jam {style}
credits:
  music: 'FM-1 Accompaniment project (a drum jam pattern)'
rights:
  composition: 'original (this project)'
  generated: tools/jam_songs.py
music:
  key: C
  time_signature: {bpb}/4
  tempo_bpm: {TEMPO[style]}
  pickup_beats: 0
  feel: {"swing" if style == "shuffle" else "straight"}
  style: {style}
form:
  - {{ section: Jam, bars: 1-{BARS + 1}, chart: a }}
layers:
  drums:
    channel: 10
    variants:
      1: the pulse
      2: a groove
      3: the groove with fills and crashes
chart:
  a: |
    {row}
    {row}
    | C |
""", bpb


def main():
    out = ["/* GENERATED by tools/jam_songs.py: SYNTH mode's drum jam patterns, one format-2.0 song per style (drums",
           " * only, 8 bars + the closing bar). Do not edit. Licence: TBD (see D017) */", "#pragma once",
           "#include <stdint.h>", ""]
    names = []
    with tempfile.TemporaryDirectory() as td:
        for style in STYLE_NAMES:
            d = Path(td) / f"jam-{style}"
            d.mkdir()
            y, bpb = yaml_of(style)
            (d / "song.yaml").write_text(y)
            (d / "song.mid").write_bytes(write_midi(480, [("conductor", [(0, meta_tempo(round(60e6 / TEMPO[style]))),
                                                                        (0, meta_timesig(bpb, 4))])]))
            blob = compile_folder(d)[0]
            out.append(f"static const uint8_t JAM_{style.upper()}[{len(blob)}] __attribute__((aligned(4))) = {{")
            for i in range(0, len(blob), 16):
                out.append("    " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 16]) + ",")
            out.append("};")
            names.append(style)
    out.append("static const struct { const char *name; const uint8_t *data; uint32_t size; } JAM_SONGS[] = {")
    out += [f'    {{"{n.upper()}", JAM_{n.upper()}, sizeof JAM_{n.upper()}}},' for n in names]
    out += ["};", f"#define JAM_BARS {BARS}u", ""]
    (ROOT / "firmware/app/jam_songs.h").write_text("\n".join(out))
    print(f"jam_songs.h: {len(names)} styles")


if __name__ == "__main__":
    main()
