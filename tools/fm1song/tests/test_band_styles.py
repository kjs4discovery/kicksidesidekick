# M9 (D052): the band's tier tables for backtracks: tools/band_styles.txt -> band_styles.h (C) and band_styles_data.py;
# the validator; the FM-1's generators (firmware/app/gen.c bt_*) and the laptop's (arrange.band_*) make the same events
# for every backtrack in each of the 11 styles at tiers 1-4.
import importlib.util
import subprocess
from pathlib import Path

import pytest

from conftest import ROOT
from fm1song import arrange as arr
from fm1song import compile_song, read_compiled
from fm1song import binformat as bf

spec = importlib.util.spec_from_file_location("band_styles", ROOT / "tools/band_styles.py")
bs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bs)
LAYERS = ("drums", "bass", "harmony", "melody")
BACKTRACKS = sorted(p for p in (ROOT / "songs/backtracks").glob("*/") if (p / "song.yaml").is_file())
TEXT = (ROOT / "tools/band_styles.txt").read_text()


# ------------------------------------------------------------------------------------------- the table and its files
def test_generated_files_are_up_to_date():
    styles = bs.parse(TEXT)
    assert bs.OUT_C.read_text() == bs.c_text(styles), "run tools/band_styles.py"
    assert bs.OUT_PY.read_text() == bs.py_text(styles), "run tools/band_styles.py"
    assert "generated by tools/band_styles.py, do not edit" in bs.OUT_C.read_text()
    assert "generated by tools/band_styles.py, do not edit" in bs.OUT_PY.read_text()


def test_the_table_has_the_11_styles_four_tiers_each():
    styles = bs.parse(TEXT)
    assert list(styles) == ["POP", "ROCK", "INDIE POP", "BALLAD", "SHUFFLE", "STRIDE", "WALTZ", "COUNTRY", "BOSSA NOVA",
                            "FUNK", "REGGAE"]
    assert all(sorted(s["tiers"]) == [1, 2, 3, 4] for s in styles.values())
    assert styles["WALTZ"]["beats"] == 3 and styles["SHUFFLE"]["steps"] == 3 and styles["SHUFFLE"]["swing"]


def _edit(old, new, count=1):
    assert old in TEXT, old
    return TEXT.replace(old, new, count)


def test_the_validator_refuses_a_bar_of_the_wrong_length_with_its_line():
    n = TEXT.splitlines().index("HARM CLOSE x-------o-------") + 1
    with pytest.raises(bs.TableError, match=rf":{n}: a bar of 15 characters, 16 wanted"):
        bs.parse(_edit("HARM CLOSE x-------o-------", "HARM CLOSE x-------o------"))
    n = TEXT.splitlines().index("HARM CLOSE ....x---x---") + 1                 # WALTZ: 3/4, 12 characters
    with pytest.raises(bs.TableError, match=rf":{n}: a bar of 16 characters, 12 wanted"):
        bs.parse(_edit("HARM CLOSE ....x---x---", "HARM CLOSE ....x---x---...."))
    with pytest.raises(bs.TableError, match="a bar of 13 characters, 12 wanted"):         # SHUFFLE: 3 steps, 12
        bs.parse(_edit("HARM CLOSE x-----x-----", "HARM CLOSE x-----x------"))


def test_the_validator_refuses_unknown_characters_missing_tiers_and_unknown_styles():
    with pytest.raises(bs.TableError, match="unknown character 'z'"):
        bs.parse(_edit("H x...x...x...x...", "H x...x...x...z..."))
    with pytest.raises(bs.TableError, match="unknown character 'x'"):                 # a bass line has no 'x'
        bs.parse(_edit("BASS R-------F-------", "BASS R-------x-------"))
    with pytest.raises(bs.TableError, match="TIER 5: the tiers come in order"):
        bs.parse(TEXT.replace("TIER 4\n", "TIER 5\n", 1))
    cut = TEXT.index("STYLE ROCK")
    pop4 = TEXT.index("TIER 4", 0)
    with pytest.raises(bs.TableError, match="TIER 4 is missing"):
        bs.parse(TEXT[:pop4] + TEXT[cut:])
    with pytest.raises(bs.TableError, match="not one of the FM-1's 11"):
        bs.parse(_edit("STYLE POP  steps 4", "STYLE DISCO  steps 4"))
    with pytest.raises(bs.TableError, match="style 'REGGAE' is missing"):
        bs.parse(TEXT[:TEXT.index("STYLE REGGAE")])


# ------------------------------------------------------------------------ C = Python, 4 tiers, 11 styles
def py_events(c, style, bpb):
    r = bf.restyled(c, style, bpb)
    return {(name, lv): [list(e) for e in bf.generate(r, name, lv)] for name in ("drums", "bass", "harmony")
            for lv in range(1, 5)}


@pytest.mark.parametrize("folder", BACKTRACKS, ids=lambda p: p.name)
def test_c_and_python_make_the_same_in_every_style_at_every_tier(folder, tmp_path):
    exe = ROOT / "build/fuzz/song_fuzz"
    if not exe.exists():
        pytest.skip("build tools/song_fuzz first (tools/song_fuzz.sh)")
    from fm1song import compile_folder
    blob = compile_folder(folder)[0]
    c = read_compiled(blob)
    assert c["version"] == "2.2" and c["kind"] == "backtrack"
    assert {n: sorted(ly["variants"]) for n, ly in c["layers"].items()} == {n: [1, 2, 3, 4] for n in
                                                                            ("drums", "bass", "harmony")}
    f = tmp_path / "s.fm1s"
    f.write_bytes(blob)
    for si, name in enumerate(arr.STYLE_NAMES):
        bpb = 3 if name == "waltz" else 4
        out = subprocess.run([str(exe), "--events", str(f), str(si), str(bpb)], capture_output=True, text=True,
                             check=True).stdout
        got = {}
        for line in out.splitlines():
            l, v, t, st, a, b = map(int, line.split())
            got.setdefault((LAYERS[l], v), []).append([t, st, a, b])
        want = py_events(c, name, bpb)
        for key, evs in want.items():
            assert got.get(key, []) == [e for e in evs if e[1] in (0x80, 0x90)], (folder.name, name, key)
            assert evs, (folder.name, name, key)             # (every tier plays something)


