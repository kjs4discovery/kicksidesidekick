#!/usr/bin/env python3
# logo_to_c.py -- the boot splash's logo: an image file -> a small C header (a palette and run-length rows).
# Licence: TBD (see D017)
#
#   logo_to_c.py IMAGE OUT.h [--width 150] [--colors 12]
#
# Run by firmware/build.sh through fm1.toml's gen = [...] on firmware/assets/tmp-logo.jpg: to change the logo,
# replace that one file (any size; it is scaled to --width, the background is its top-left pixel's colour).
# The image is scaled, reduced to a few colours (no dithering: flat runs) and stored as runs: a byte
# (colour << 4 | run - 1) for runs of 1..15, (colour << 4 | 15) + a byte n for a run of 16 + n (16..271).
# ui.c draw_splash() draws it. A placeholder logo (the user's, 2026-11-05) costs a few KB of flash.
import argparse
from pathlib import Path

from PIL import Image


def rgb565(c):
    r, g, b = c[:3]
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("image")
    ap.add_argument("out")
    ap.add_argument("--width", type=int, default=150)
    ap.add_argument("--colors", type=int, default=8)
    a = ap.parse_args()
    im = Image.open(a.image).convert("RGB")
    h = round(im.height * a.width / im.width)
    im = im.resize((a.width, h), Image.LANCZOS)
    q = im.quantize(colors=min(a.colors, 16), method=Image.Quantize.MAXCOVERAGE, dither=Image.Dither.NONE)
    pal = q.getpalette()[:3 * min(a.colors, 16)]
    px = list(q.get_flattened_data() if hasattr(q, "get_flattened_data") else q.getdata())
    bg = px[0]
    data = bytearray()
    for y in range(h):
        row = px[y * a.width:(y + 1) * a.width]
        x = 0
        while x < a.width:
            c, n = row[x], 1
            while x + n < a.width and row[x + n] == c and n < 271:
                n += 1
            data += bytes([c << 4 | (n - 1)]) if n <= 15 else bytes([c << 4 | 15, n - 16])
            x += n
    colors = [rgb565(pal[3 * i:3 * i + 3]) for i in range(len(pal) // 3)]
    lines = ["/* generated by tools/logo_to_c.py from " + Path(a.image).name + ": do not edit */", "#pragma once",
             "#include <stdint.h>", f"#define LOGO_W {a.width}u", f"#define LOGO_H {h}u",
             f"#define LOGO_BG 0x{colors[bg]:04X}u",
             "static const uint16_t LOGO_PAL[16] = {" + ", ".join(f"0x{c:04X}u" for c in colors) + "};",
             f"static const uint8_t LOGO_RLE[{len(data)}] = {{"]
    for k in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[k:k + 24]) + ",")
    lines.append("};")
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"logo_to_c: {Path(a.image).name} -> {a.width}x{h}, {len(colors)} colours, {len(data)} bytes")


if __name__ == "__main__":
    main()
