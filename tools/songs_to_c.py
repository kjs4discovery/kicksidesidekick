#!/usr/bin/env python3
# songs_to_c.py -- M1: compile every song folder and bundle the .fm1s files into the firmware as one C header.
# Licence: TBD (see D017)
#
#   songs_to_c.py SONGS_DIR OUT.h
#
# Run by firmware/build.sh through fm1.toml's gen = [...]. The songs become const arrays in the app image (the
# flash, read in place by firmware/app/song.c): covered by the package's own checks, no new flash layout. The device
# checks each one when it is first opened (song_open), not at boot. `fm1song send` (step 1.7) replaces this.
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fm1song import SongError, compile_folder, read_compiled   # noqa: E402

MAX_TOTAL = 160 * 1024            # what the app slot has room for next to EAS (docs/firmware.md, M1)


def main(src, out):
    folders = sorted(p for p in Path(src).iterdir() if (p / "song.yaml").is_file())
    songs = []
    for f in folders:
        try:
            blob, diag = compile_folder(f)
        except SongError as e:
            raise SystemExit(f"songs_to_c: {f.name}:\n{e}")
        for d in diag.items:
            print(f"songs_to_c: {f.name}: {d}", file=sys.stderr)
        songs.append((read_compiled(blob)["title"], f.name, blob))
    songs.sort(key=lambda s: s[0].lower())        # the song list's order: by title
    total = sum(len(b) for _, _, b in songs)
    if total > MAX_TOTAL:
        raise SystemExit(f"songs_to_c: {total} bytes of songs, more than {MAX_TOTAL}")
    lines = ["/* generated by tools/songs_to_c.py from songs/: do not edit */", "#pragma once",
             "#include <stdint.h>", ""]
    for i, (title, slug, blob) in enumerate(songs):
        lines.append(f"/* {title} ({slug}): {len(blob)} bytes */")
        lines.append(f"static const uint8_t SONG_FILE_{i}[{len(blob)}] __attribute__((aligned(4))) = {{")
        for k in range(0, len(blob), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in blob[k:k + 24]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("static const struct { const uint8_t *data; uint32_t size; } SONG_FILES[] = {")
    lines += [f"    {{SONG_FILE_{i}, {len(b)}u}}," for i, (_, _, b) in enumerate(songs)]
    lines.append("};")
    lines.append(f"#define SONG_FILES_N {len(songs)}u")
    lines.append(f"#define SONG_FILES_BYTES {total}u")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"songs_to_c: {len(songs)} songs, {total} bytes -> {Path(out).name}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: songs_to_c.py SONGS_DIR OUT.h")
    main(sys.argv[1], sys.argv[2])
