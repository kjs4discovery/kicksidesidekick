#!/usr/bin/env python3
# jam_patterns.py -- M7 Part 4 (D041): SYNTH mode's drum patterns, from the readable grid docs/drum-patterns.txt, as
# firmware/app/jam_patterns.h (const tables for synth.c's sequencer). Laptop only.
# SPDX-License-Identifier: GPL-3.0-or-later
#
#   .venv/bin/python -I tools/jam_patterns.py [docs/drum-patterns.txt] [firmware/app/jam_patterns.h]
#   .venv/bin/python -I tools/jam_patterns.py --md     the grids as Markdown (for docs/controls.md)
#
# A pattern: a name (up to 11 characters), beats a bar (2..7), steps a bar (12 or 16; at most 16), 1 or 2 bars; per
# step one u16: 8 instruments x 2 bits of velocity (bits 2i..2i+1: instrument i; 0 rest, 1 ghost, 2 normal,
# 3 accent). 4 + 12 + 2 x 16 x 2 = 80 bytes a pattern at most (a 1-bar pattern: 48).
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INSTR = ["KICK", "SNARE", "CHH", "OHH", "CLAP", "TOMLO", "TOMHI", "RIM"]
VEL = {".": 0, "g": 1, "o": 2, "x": 3}
ROCK1 = "ROCK1"


def parse(text):
    pats, cur = [], None
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        where = f"line {n}"
        w = line.split()
        if w[0] == "pattern":
            if len(w) != 4:
                raise SystemExit(f"{where}: pattern NAME BEATS STEPS")
            name, beats, steps = w[1], int(w[2]), int(w[3])
            if not (1 <= len(name) <= 11 and name.isascii() and name == name.upper()):
                raise SystemExit(f"{where}: name {name!r}: 1..11 capitals")
            if not 2 <= beats <= 7 or steps not in (12, 16):
                raise SystemExit(f"{where}: {beats} beats, {steps} steps: 2..7 beats, 12 or 16 steps (a whole number a "
                                 f"beat)")
            if steps % beats:
                raise SystemExit(f"{where}: {steps} steps do not divide into {beats} beats")
            cur = {"name": name, "beats": beats, "steps": steps, "rows": {}, "bars": None, "line": n}
            pats.append(cur)
            continue
        if cur is None:
            raise SystemExit(f"{where}: a row before the first pattern")
        inst = w[0].upper()
        if inst not in INSTR:
            raise SystemExit(f"{where}: instrument {w[0]!r}: one of {' '.join(INSTR)}")
        if inst in cur["rows"]:
            raise SystemExit(f"{where}: {inst} twice in {cur['name']}")
        bars = "".join(w[1:]).split("|")
        if cur["bars"] is None:
            cur["bars"] = len(bars)
        if len(bars) != cur["bars"] or len(bars) not in (1, 2):
            raise SystemExit(f"{where}: {len(bars)} bars; every row of {cur['name']} has the same 1 or 2")
        cells = []
        for b in bars:
            if len(b) != cur["steps"]:
                raise SystemExit(f"{where}: a bar of {len(b)} steps, {cur['name']} has {cur['steps']}")
            for c in b:
                if c not in VEL:
                    raise SystemExit(f"{where}: {c!r}: x o g or .")
                cells.append(VEL[c])
        cur["rows"][inst] = cells
    names = [p["name"] for p in pats]
    if len(set(names)) != len(names):
        raise SystemExit("two patterns with one name")
    for p in pats:
        if not p["rows"]:
            raise SystemExit(f"{p['name']}: no rows")
        n = p["bars"] * p["steps"]
        p["words"] = [sum(p["rows"].get(inst, [0] * n)[k] << 2 * i for i, inst in enumerate(INSTR)) for k in range(n)]
        if not any(p["words"]):
            raise SystemExit(f"{p['name']}: silent")
    if ROCK1 not in names:
        raise SystemExit("ROCK1 (the default) is missing")
    return pats


def header(pats):
    out = ["/* SPDX-License-Identifier: GPL-3.0-or-later */",
           "/* GENERATED by tools/jam_patterns.py from docs/drum-patterns.txt: do not edit. SYNTH mode's drum patterns",
           " * (M7 Part 4, D041), ours. Per step a u16: instrument i's velocity in bits 2i..2i+1 (0 rest, 1 ghost, 2 normal,",
           " * 3 accent); instruments KICK SNARE CHH OHH CLAP TOMLO TOMHI RIM. */",
           "#pragma once", "#include <stdint.h>", "",
           "struct jam_pattern {",
           "    char name[12];",
           "    uint8_t beats, steps, bars, pad;     /* beats a bar, steps a bar (12 or 16), 1 or 2 bars */",
           "    uint16_t step[32];",
           "};", "",
           f"#define JAM_PATTERNS {len(pats)}u",
           f"#define JAM_DEFAULT {[p['name'] for p in pats].index(ROCK1)}u   /* ROCK1 */",
           "static const struct jam_pattern JAM[JAM_PATTERNS] = {"]
    for p in pats:
        words = ", ".join(f"0x{w:04x}" for w in p["words"])
        out.append(f'    {{"{p["name"]}", {p["beats"]}, {p["steps"]}, {p["bars"]}, 0, {{{words}}}}},')
    out += ["};", ""]
    return "\n".join(out)


def markdown(pats):
    out = []
    for p in pats:
        out.append(f"**{p['name']}** ({p['beats']} beats, {p['steps']} steps a bar, {p['bars']} bar"
                   f"{'s' if p['bars'] > 1 else ''})\n\n```text")
        for inst in INSTR:
            if inst in p["rows"]:
                cells = "".join(".gox"[v] for v in p["rows"][inst])
                bars = [cells[k:k + p["steps"]] for k in range(0, len(cells), p["steps"])]
                out.append(f"{inst:<6}" + "|".join(bars))
        out.append("```\n")
    return "\n".join(out)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    src = Path(args[0]) if args else ROOT / "docs/drum-patterns.txt"
    pats = parse(src.read_text())
    if "--md" in sys.argv:
        print(markdown(pats))
        return
    dst = Path(args[1]) if len(args) > 1 else ROOT / "firmware/app/jam_patterns.h"
    dst.write_text(header(pats))
    print(f"jam_patterns: {len(pats)} patterns -> {dst}")


if __name__ == "__main__":
    main()
